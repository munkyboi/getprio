const test = require('node:test');
const assert = require('node:assert/strict');
const { createStaffWriterFixture } = require('./helpers/staffWriterFixture.cjs');
const { createStaffInvitationResourceService } = require('../src/services/staffInvitationResourceService');
const databaseUrl = process.env.RESOURCE_LEDGER_TEST_DATABASE_URL;

test('staff invitation admission and resource effects share one PostgreSQL transaction', { skip: !databaseUrl, timeout: 60000 }, async t => {
  const f = createStaffWriterFixture(databaseUrl, 'invitation');
  const { pool, wrappedPool, transaction, waiter, hold, revisions } = f;
  const service = createStaffInvitationResourceService({ pool: wrappedPool });
  const input = { tenant: { _id: '1', name: 'Studio' }, actorId: '1', userId: '3', email: 'other@example.test', role: 'staff' };
  const invite = changes => service.invite({ ...input, ...changes });
  async function reset() {
    await f.reset();
    await pool.query(`UPDATE subscription_plans SET entitlements='{"staffSeats":5}';
      SELECT setval(pg_get_serial_sequence('tenant_memberships','id'),3)`);
  }
  const newMembers = async () => (await pool.query('SELECT 1 FROM tenant_memberships WHERE user_id=3 AND tenant_id=1')).rowCount;
  const notices = async () => (await pool.query('SELECT 1 FROM staff_access_email_outbox')).rowCount;
  const unchanged = async () => { assert.equal(await newMembers(), 0); assert.equal(await notices(), 0); assert.ok((await revisions()).every(row => row.revision === '1')); };
  async function finish(client, commit = false) { await client.query(commit ? 'COMMIT' : 'ROLLBACK'); client.release(); }
  try {
    await f.initialize();
    await pool.query(`ALTER TABLE tenant_memberships ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
      ALTER TABLE tenant_memberships ADD UNIQUE(user_id,tenant_id)`);
    await t.test('unassigned staff has no invented branch access while admin access revises all vendor branches', async () => {
      await reset(); await invite();
      assert.equal(await newMembers(), 1); assert.equal(await notices(), 1);
      assert.deepEqual((await revisions()).map(row => row.revision), ['1','1','1','1']);
      await reset(); await invite({ role: 'admin' });
      assert.deepEqual((await revisions()).map(row => row.revision), ['2','2','2','1']);
    });
    await t.test('current administrator role admits only ordinary staff on the actual service', async () => {
      for (const role of ['admin','owner']) {
        await reset(); await pool.query("UPDATE tenant_memberships SET role='admin' WHERE id=1");
        await assert.rejects(invite({ role }), error => error.statusCode === 403); await unchanged();
      }
      await reset(); await pool.query("UPDATE tenant_memberships SET role='admin' WHERE id=1");
      await invite(); assert.equal(await newMembers(), 1);
    });
    await t.test('preexisting active counter grants affect only this vendor; inactive and foreign grants remain distinct', async () => {
      await reset();
      await pool.query(`UPDATE service_counters SET is_active=FALSE WHERE id=2;
        INSERT INTO service_counter_assignments VALUES(1,3),(2,3),(3,3)`);
      await invite();
      assert.deepEqual((await revisions()).map(row => row.revision), ['2','1','1','1']);
    });
    await t.test('committed actor revocation, target flags and email change after root wait reject stale preflight', async () => {
      for (const sql of ["UPDATE tenant_memberships SET role='staff' WHERE id=1", "UPDATE users SET deletion_requested_at='2026-01-01' WHERE id=3", "UPDATE users SET platform_access_suspended_at='2026-01-01' WHERE id=3", "UPDATE users SET email='changed@example.test' WHERE id=3"]) {
        await reset(); const writer = await transaction();
        try {
          await writer.query('SELECT id FROM tenants WHERE id=1 FOR UPDATE');
          const pending = invite(); const outcome = assert.rejects(pending, error => [403,409].includes(error.statusCode));
          await waiter('FROM tenants'); await writer.query(sql); await writer.query('COMMIT');
          await outcome; await unchanged();
        } finally { await finish(writer); }
      }
    });
    await t.test('admission-first holds actor grants and target identity through membership and notices', async () => {
      await reset(); const gate = hold('SELECT id FROM users WHERE id=$1 FOR UPDATE NOWAIT');
      const reader = invite(); const writer = await transaction();
      try {
        await gate.entered;
        const changed = writer.query("UPDATE users SET email='later@example.test' WHERE id=3");
        await waiter('UPDATE users'); gate.release(); await reader; await changed; await writer.query('COMMIT');
        assert.equal(await newMembers(), 1); assert.equal(await notices(), 1);
      } finally { gate.release(); await finish(writer); }
    });
    await t.test('new assignment admitted before invitation is included; assignment after target upgrade waits', async () => {
      await reset(); await pool.query('INSERT INTO service_counter_assignments VALUES(1,3)'); await invite();
      assert.deepEqual((await revisions()).map(row => row.revision), ['2','1','1','1']);
      await reset(); const gate = hold('SELECT id FROM users WHERE id=$1 FOR UPDATE NOWAIT');
      const reader = invite(); const writer = await transaction();
      try {
        await gate.entered;
        const inserted = writer.query('INSERT INTO service_counter_assignments VALUES(1,3)');
        await waiter('INSERT INTO service_counter_assignments'); gate.release(); await reader; await inserted;
        // A later assignment needs its own authoritative writer; this fixture rolls it back.
        await writer.query('ROLLBACK');
        assert.equal(await newMembers(), 1); assert.ok((await revisions()).every(row => row.revision === '1'));
      } finally { gate.release(); await finish(writer); }
    });
    await t.test('legacy target-FK-first inverse returns busy without membership or notices and permits fresh retry', async () => {
      await reset(); const writer = await transaction();
      await writer.query('INSERT INTO service_counter_assignments VALUES(1,3)');
      const gate = hold('FROM tenants WHERE id=$1 FOR UPDATE'); const reader = invite();
      const outcome = assert.rejects(reader, error => error.code === 'STAFF_INVITATION_BUSY');
      try {
        await gate.entered;
        const tenantWait = writer.query('SELECT id FROM tenants WHERE id=1 FOR UPDATE');
        await waiter('FROM tenants'); gate.release(); await outcome;
        await tenantWait; await writer.query('COMMIT'); await unchanged();
        await invite(); assert.equal(await newMembers(), 1); assert.equal(await notices(), 1);
      } finally { gate.release(); await finish(writer); }
    });
    await t.test('inactive counter activation and assignment deletion wait for inventoried row holds', async () => {
      for (const sql of ['UPDATE service_counters SET is_active=TRUE WHERE id=1', 'DELETE FROM service_counter_assignments WHERE counter_id=1 AND user_id=3']) {
        await reset(); await pool.query('UPDATE service_counters SET is_active=FALSE WHERE id=1');
        await pool.query('INSERT INTO service_counter_assignments VALUES(1,3)');
        const gate = hold('FOR SHARE OF a,c NOWAIT'); const reader = invite(); const writer = await transaction();
        try {
          await gate.entered; const changed = writer.query(sql); await waiter(sql.split(' WHERE')[0]);
          gate.release(); await reader; await changed; await writer.query('ROLLBACK');
          assert.equal(await newMembers(), 1); assert.ok((await revisions()).every(row => row.revision === '1'));
        } finally { gate.release(); await finish(writer); }
      }
    });
    await t.test('membership revision and notice failures all roll back the admission', async () => {
      for (const marker of ['INSERT INTO tenant_memberships', 'UPDATE resource_ledger_scopes', 'INSERT INTO staff_access_email_outbox']) {
        await reset(); await pool.query('INSERT INTO service_counter_assignments VALUES(1,3)'); f.fault = marker;
        await assert.rejects(invite(), /invitation writer fault/u); f.fault = null; await unchanged();
      }
    });
    await t.test('current subscription and plan policy remain held, with no default-pool entitlement read', async () => {
      await reset(); const gate = hold('SELECT slug FROM subscription_plans WHERE slug=$1 FOR SHARE NOWAIT');
      const reader = invite(); const writer = await transaction();
      try {
        await gate.entered; const changed = writer.query(`UPDATE subscription_plans SET entitlements='{"staffSeats":0}'`);
        await waiter('UPDATE subscription_plans'); gate.release(); await reader; await changed; await writer.query('COMMIT');
        assert.equal(await newMembers(), 1);
      } finally { gate.release(); await finish(writer); }
      await reset(); await pool.query(`UPDATE subscription_plans SET entitlements='{"staffSeats":1}'`);
      await assert.rejects(invite(), error => error.statusCode === 403); await unchanged();
    });
    await t.test('unavailable notice recipients and foreign counter scopes fail before admission', async () => {
      await reset(); await pool.query("UPDATE tenant_memberships SET role='owner' WHERE id=2");
      await pool.query("UPDATE users SET deletion_requested_at='2026-01-01' WHERE id=2");
      await assert.rejects(invite(), error => error.code === 'STAFF_NOTICE_RECIPIENT_UNAVAILABLE'); await unchanged();
      await reset(); await pool.query('UPDATE service_counters SET location_id=20 WHERE id=1');
      await pool.query('INSERT INTO service_counter_assignments VALUES(1,3)');
      await assert.rejects(invite(), /counter scope requires reconciliation/u); await unchanged();
    });
    await t.test('exact adjacent BIGINT accounts and vendors remain distinct with zero branches', async () => {
      await reset();
      await pool.query(`INSERT INTO tenants VALUES(9007199254740992),(9007199254740993);
        INSERT INTO users(id,roles,name,email,email_verified) VALUES(9007199254740992,'{}','A','a@example.test',TRUE),(9007199254740993,'{}','B','b@example.test',TRUE);
        INSERT INTO tenant_memberships VALUES(4,1,9007199254740992,'owner',TRUE),(5,1,9007199254740993,'owner',TRUE);
        SELECT setval(pg_get_serial_sequence('tenant_memberships','id'),5);
        INSERT INTO tenant_subscriptions(id,tenant_id,status,plan_slug,entitlements,updated_at) VALUES(2,9007199254740992,'active','pro','{}',NOW()),(3,9007199254740993,'active','pro','{}',NOW())`);
      for (const [id,email] of [['9007199254740992','a@example.test'],['9007199254740993','b@example.test']]) {
        await invite({ tenant: { _id: id, name: "Large vendor" }, userId: id, email });
      }
      assert.deepEqual((await pool.query("SELECT user_id::text,tenant_id::text FROM tenant_memberships WHERE user_id>9007199254740991 ORDER BY user_id")).rows,
        [{ user_id:'9007199254740992',tenant_id:'9007199254740992' },{ user_id:'9007199254740993',tenant_id:'9007199254740993' }]);
      assert.equal(await notices(), 2); assert.ok((await revisions()).every(row => row.revision === '1'));
      await assert.rejects(invite({ userId: 9007199254740992 }), error => error.statusCode === 400);
    });
    await t.test('reciprocal cross-vendor target upgrades return promptly without collateral actor changes', async () => {
      await reset(); await pool.query("INSERT INTO tenant_memberships(id,user_id,tenant_id,role,is_active) VALUES(4,3,2,'owner',TRUE)");
      await pool.query("SELECT setval(pg_get_serial_sequence('tenant_memberships','id'),4)");
      let release, entered; const gate = new Promise(resolve => { release = resolve; });
      const bothEntered = new Promise(resolve => { entered = resolve; }); let count = 0;
      const coordinatedPool = { connect: async () => {
        const client = await pool.connect();
        return { release: () => client.release(), query: async (sql, values) => {
          const result = await client.query(sql, values);
          if (sql.includes('FROM users WHERE id=ANY')) { count++; if (count === 2) entered(); await gate; }
          return result;
        } };
      } };
      const concurrent = createStaffInvitationResourceService({ pool: coordinatedPool });
      const one = concurrent.invite(input), two = concurrent.invite({ ...input, tenant: { _id: '2', name: 'Other vendor' }, actorId: '3', userId: '1', email: 'owner@example.test' });
      const settled = Promise.allSettled([one,two]);
      await bothEntered; release(); const results = await settled;
      const rejected = results.filter(row => row.status === 'rejected');
      assert.ok(rejected.length >= 1); assert.ok(rejected.every(row => row.reason.code === 'STAFF_INVITATION_BUSY'));
      const successes = results.filter(row => row.status === 'fulfilled').length;
      assert.equal((await pool.query('SELECT 1 FROM staff_access_email_outbox')).rowCount, successes);
      assert.deepEqual((await pool.query('SELECT role FROM tenant_memberships WHERE id IN (1,4) ORDER BY id')).rows, [{ role:'owner' },{ role:'owner' }]);
      assert.ok((await revisions()).every(row => row.revision === '1'));
    });
  } finally { await f.dispose(); }
});
