const BOOKING_EVENTS = new Set([
  "confirmed", "rescheduled", "canceled", "no_show", "checked_in", "completed",
  "payment_rejected", "payment_verified", "pending_expired", "check_in_window_open",
  "check_in_closing", "updated", "reminder_24h", "reminder_1h"
].map(action => `customer_booking_${action}`));
const QUEUE_EVENTS = new Set([
  ...["joined", "confirmed", "called", "service_started", "service_completed", "service_interrupted",
    "served", "skipped", "cancelled", "unserved", "requeued", "near_turn", "carried_over",
    "pending_carry_over", "expired", "updated"].map(action => `customer_queue_${action}`),
  ...["waiting", "called", "confirmed", "served", "skipped", "cancelled", "unserved", "expired",
    "invitation", "near_turn", "updated"].map(action => `developer_ticket_${action}`)
]);

// These namespaces are generated by server outbox/reminder producers. Neither
// title/body nor client-supplied display labels are type evidence.
function keyKind(key) {
  if (typeof key !== "string") return null;
  if (/^booking:[1-9]\d*:schedule:[1-9]\d*:reminder:(24h|1h)$/u.test(key)) return "booking";
  if (/^queue-event:[1-9]\d*:.+$/u.test(key) || /^queue-intent:.+$/u.test(key)) return "queue";
  return null;
}
function notificationKind({notificationKey, eventType}) {
  const fromKey = keyKind(notificationKey);
  const fromEvent = BOOKING_EVENTS.has(eventType) ? "booking" : QUEUE_EVENTS.has(eventType) ? "queue" : null;
  if (fromKey && fromEvent && fromKey !== fromEvent) return "general";
  return fromEvent || fromKey || "general";
}
module.exports = {notificationKind};
