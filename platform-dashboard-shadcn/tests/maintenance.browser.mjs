export default async function verify(page) {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('http://127.0.0.1:5194/tests/maintenance-harness.html?failure')
  const pause = page.getByRole('checkbox', { name: 'Pause new bookings and queue joins' })
  const screen = page.getByRole('checkbox', { name: 'Show full maintenance screen on public/customer pages' })
  await pause.waitFor()
  const hitArea = await pause.evaluate(el => { const s = getComputedStyle(el, '::after'); return { width: parseFloat(s.width), height: parseFloat(s.height) } })
  if (hitArea.width < 44 || hitArea.height < 44) throw new Error('Checkbox hit target must be at least 44 by 44 pixels')
  if (!await screen.isDisabled()) throw new Error('Forced screen must require maintenance')
  await pause.check(); await screen.check()
  await page.getByLabel('Public maintenance message').fill('Planned maintenance. Existing services can continue.')
  const review = page.getByRole('button', { name: 'Review maintenance change' })
  if (!await review.isDisabled()) throw new Error('An audit reason is required')
  await page.getByLabel('Audit reason').fill('Scheduled safe maintenance window')
  await review.click()
  const dialog = page.getByRole('dialog')
  await dialog.waitFor()
  if (!await page.locator('#maintenance-enabled').isDisabled()) throw new Error('Draft cannot change after preview')
  await dialog.getByRole('button', { name: 'Confirm maintenance change' }).click()
  await dialog.getByText('Simulated network failure').waitFor()
  await page.keyboard.press('Escape')
  if (!await dialog.isVisible()) throw new Error('An uncertain committed save must retain its retry identity')
  await dialog.getByRole('button', { name: 'Confirm maintenance change' }).click()
  await dialog.waitFor({ state: 'hidden' })
  const saved = JSON.parse(await page.getByLabel('Saved maintenance policy').textContent())
  if (!saved.enabled || !saved.forceScreen || saved.revision !== '2') throw new Error('Review did not save both settings')
  if (await page.locator('body').evaluate(el => el.scrollWidth > window.innerWidth)) throw new Error('Admin maintenance form overflows mobile')
  await page.screenshot({path:'maintenance-admin-mobile.png',fullPage:true})
  await pause.uncheck()
  if (await screen.isChecked()) throw new Error('Ending maintenance must clear the forced screen')
  await page.getByLabel('Audit reason').fill('Maintenance completed successfully')
  await review.click(); await dialog.getByRole('button', { name: 'Confirm maintenance change' }).click()
  await dialog.waitFor({ state: 'hidden' })
  const stopped = JSON.parse(await page.getByLabel('Saved maintenance policy').textContent())
  if (stopped.enabled || stopped.forceScreen) throw new Error('Maintenance did not end')
  await page.goto('http://127.0.0.1:5194/tests/maintenance-harness.html?failure')
  await pause.waitFor(); await pause.check()
  await page.getByLabel('Audit reason').fill('Reconcile a committed save response')
  await review.click(); await dialog.getByRole('button', { name: 'Confirm maintenance change' }).click()
  await dialog.getByText('Simulated network failure').waitFor()
  await dialog.getByRole('button', { name: 'Check saved status' }).click()
  await dialog.waitFor({ state: 'hidden' })
  if (!await pause.isChecked() || !await review.isDisabled()) throw new Error('Reconciliation must reflect the committed status without a new write')
  await page.goto('http://127.0.0.1:5194/tests/maintenance-harness.html?failure&pending&denied')
  await pause.waitFor(); await pause.check()
  await page.getByLabel('Audit reason').fill('Resolve a still-pending operation')
  await review.click(); await dialog.getByRole('button', { name: 'Confirm maintenance change' }).click()
  await dialog.getByText('Simulated network failure').waitFor()
  await dialog.getByRole('button', { name: 'Check saved status' }).click()
  await dialog.getByText('This save has no committed receipt yet. Keep this confirmation and retry to resolve it safely.').waitFor()
  if (!await dialog.isVisible()) throw new Error('Missing receipt must not resolve a pending save')
  await dialog.getByRole('button', { name: 'Confirm maintenance change' }).click()
  await dialog.getByText('Simulated retry denial').waitFor()
  if (!await dialog.isVisible()) throw new Error('A denied retry cannot resolve the original uncertain operation')
  await dialog.getByRole('button', { name: 'Confirm maintenance change' }).click()
  await dialog.waitFor({state:'hidden'})
  await page.goto('http://127.0.0.1:5194/tests/maintenance-harness.html?failure&pending&denied')
  await pause.waitFor(); await pause.check()
  await page.getByLabel('Audit reason').fill('Discard an expired uncertain confirmation safely')
  await review.click(); await dialog.getByRole('button', { name: 'Confirm maintenance change' }).click()
  await dialog.getByText('Simulated network failure').waitFor()
  await dialog.getByRole('button', { name: 'Confirm maintenance change' }).click()
  await dialog.getByText('Simulated retry denial').waitFor()
  await dialog.getByRole('button', { name: 'Safely discard confirmation' }).click()
  await dialog.waitFor({state:'hidden'})
  await page.getByText('Confirmation safely discarded. A delayed save cannot apply it.').waitFor()
  if (await pause.isChecked()) throw new Error('Abandonment must restore current saved policy')
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('http://127.0.0.1:5194/tests/maintenance-harness.html?readonly')
  await pause.waitFor()
  if (!await pause.isDisabled() || !await review.isDisabled()) throw new Error('Read-only viewers cannot edit maintenance')
  await page.screenshot({path:'maintenance-admin-desktop.png',fullPage:true})
}
